from playwright.sync_api import sync_playwright,expect
from pathlib import Path
import json,sys,re
sys.stdout.reconfigure(encoding='utf-8')
out=Path('.qa');out.mkdir(exist_ok=True)
checks=[];errors=[]
def passed(name):checks.append(name);print('PASS:',name,flush=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,args=['--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    context=browser.new_context(viewport={'width':1440,'height':1100},device_scale_factor=1)
    page=context.new_page();page.on('pageerror',lambda err:errors.append(str(err)))
    page.goto('http://127.0.0.1:4173');page.wait_for_load_state('networkidle')
    page.get_by_role('button',name='หยุดชั่วคราว',exact=True).click()
    expect(page.locator('#world canvas')).to_be_visible()
    page.screenshot(path=str(out/'desktop.png'),full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    passed('Desktop, local fonts, WebGL scene, no page overflow')
    before=page.evaluate('labflow.engine.time')
    page.get_by_role('button',name='+1 นาที',exact=True).click()
    assert abs(page.evaluate('labflow.engine.time')-before-60)<.01
    passed('Pause and step advance deterministic simulation clock')
    page.get_by_label('เลือกผู้รับบริการ',exact=True).select_option(index=1)
    expect(page.locator('#inspector')).to_contain_text('ครั้งรับบริการ')
    expect(page.locator('#inspector')).to_contain_text('สิ่งส่งตรวจ')
    page.screenshot(path=str(out/'linked-paths.png'),full_page=True)
    passed('Linked patient, encounter, order, specimen paths')
    count=page.evaluate('labflow.engine.patients.length')
    page.get_by_role('button',name='เพิ่มผู้รับบริการ',exact=True).click()
    page.get_by_label('ระดับความเร่งด่วน').select_option('STAT')
    page.locator('#confirm-action').click()
    assert page.evaluate('labflow.engine.patients.length')==count+1
    passed('Add synthetic STAT patient through dialog')
    page.get_by_label('ทดลองสถานการณ์').select_option('tube')
    page.get_by_role('button',name='ใช้สถานการณ์',exact=True).click()
    expect(page.locator('#incidents')).to_contain_text('กระสวยหยุด')
    page.get_by_role('button',name='คืนระบบปกติ',exact=True).click()
    assert not page.evaluate('labflow.engine.flags.tubeDown')
    passed('Pneumatic outage and restore scenario controls')
    page.get_by_role('navigation',name='หน้าจอหลัก').get_by_role('button',name=re.compile('^LIS')).click()
    page.get_by_label('อนุมัติอัตโนมัติ',exact=True).uncheck()
    page.get_by_label('กรองผลตรวจ').select_option('complete')
    page.locator('#results-body [data-result-id]').first.click()
    page.get_by_role('button',name='สร้างฉบับแก้ไข',exact=True).click()
    page.get_by_label('เหตุผลที่แก้ไข').fill('ทบทวนผลหลังตรวจซ้ำในแบบจำลอง')
    page.locator('#confirm-action').click()
    corrected=page.evaluate('labflow.engine.results.find(r=>r.version===2).id')
    page.get_by_role('button',name='+1 นาที',exact=True).click()
    page.get_by_label('กรองผลตรวจ').select_option('approval')
    expect(page.locator('#results-body')).to_contain_text('รออนุมัติ')
    page.locator(f'#results-body [data-approve="{corrected}"]').click()
    for i in range(8):page.get_by_role('button',name='+1 นาที',exact=True).click()
    page.get_by_label('กรองผลตรวจ').select_option('all')
    page.screenshot(path=str(out/'lis.png'),full_page=True)
    assert page.evaluate('labflow.engine.results.some(r=>r.version===2 && r.releasedVersion===2)')
    passed('Versioned correction and manual authorization through LIS')
    with page.expect_download() as download:
        page.get_by_role('button',name='ส่งออก CSV',exact=True).click()
    download.value.save_as(out/'results.csv')
    assert (out/'results.csv').read_text(encoding='utf-8-sig').startswith('"patient_id"')
    passed('CSV export includes linked IDs and LIS/HIS versions')
    page.get_by_role('button',name='ประสิทธิภาพ',exact=True).click()
    expect(page.locator('#analytics')).to_contain_text('P95')
    page.screenshot(path=str(out/'metrics.png'),full_page=True)
    passed('TAT, SLA, queue and resource analytics')
    page.get_by_role('button',name='ตั้งค่าระบบ',exact=True).click()
    page.get_by_label('ความจุภาชนะ / เที่ยว',exact=False).fill('3')
    page.get_by_role('button',name='บันทึกและใช้ค่าระบบ',exact=True).click()
    assert page.evaluate('labflow.engine.config.tube.capacity')==3
    page.get_by_label('ความจุภาชนะ / เที่ยว',exact=False).fill('1.5')
    page.get_by_role('button',name='บันทึกและใช้ค่าระบบ',exact=True).click()
    expect(page.locator('#toast')).to_contain_text('จำนวนเต็ม')
    assert page.evaluate('labflow.engine.config.tube.capacity')==3
    page.get_by_label('ความจุภาชนะ / เที่ยว',exact=False).fill('3')
    with page.expect_download() as download:
        page.get_by_role('button',name='ส่งออกค่าระบบ',exact=True).click()
    download.value.save_as(out/'config.json')
    assert json.loads((out/'config.json').read_text(encoding='utf-8'))['tube']['capacity']==3
    page.locator('#config-file').set_input_files(out/'config.json')
    expect(page.locator('#toast')).to_contain_text('ใช้ค่าระบบแล้ว')
    page.screenshot(path=str(out/'settings.png'),full_page=True)
    passed('Configuration validation, local persistence, JSON import/export')
    page.get_by_label('คู่มือและแหล่งอ้างอิง').click()
    expect(page.locator('#help-dialog')).to_be_visible()
    assert page.locator('#sources a').count()==6
    page.get_by_label('ปิดคู่มือ').click()
    passed('Help and primary-source references accessible')
    mobile=context.new_page();mobile.set_viewport_size({'width':390,'height':844})
    mobile.on('pageerror',lambda err:errors.append(str(err)))
    mobile.goto('http://127.0.0.1:4173');mobile.wait_for_load_state('networkidle')
    mobile.get_by_role('button',name='หยุดชั่วคราว',exact=True).click()
    assert mobile.evaluate('document.documentElement.scrollWidth <= innerWidth')
    mobile.screenshot(path=str(out/'mobile.png'),full_page=True)
    mobile.get_by_role('button',name='ตั้งค่าระบบ',exact=True).click()
    assert mobile.evaluate('document.documentElement.scrollWidth <= innerWidth')
    mobile.screenshot(path=str(out/'mobile-settings.png'),full_page=True)
    passed('390px mobile layout and settings without page overflow')
    assert not errors,errors
    browser.close()
    fallback_browser=p.chromium.launch(headless=True,args=['--disable-webgl'])
    fallback_page=fallback_browser.new_page(viewport={'width':1280,'height':900})
    fallback_page.goto('http://127.0.0.1:4173');fallback_page.wait_for_load_state('networkidle')
    expect(fallback_page.locator('.fallback-map')).to_be_visible()
    fallback_page.get_by_role('button',name=re.compile('01 ขึ้นบัตร')).click()
    expect(fallback_page.locator('#inspector')).to_contain_text('กำลังรองรับ')
    fallback_page.screenshot(path=str(out/'fallback.png'),full_page=True)
    fallback_browser.close()
    passed('2D fallback preserves workflow and station inspection')
(out/'browser-report.json').write_text(json.dumps({'checks':checks,'errors':errors},ensure_ascii=False,indent=2),encoding='utf-8')
print(f'{len(checks)} browser checks passed; no page errors')
